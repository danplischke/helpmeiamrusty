//! The learner's working copies live in `work/`, a Cargo package the runner generates.
//! Course content in `modules/` is never edited, so pulling course updates can't conflict.
//! `work/` is a standalone workspace with its own lockfile, which only the learner touches.

use std::fs;
use std::path::Path;

use anyhow::{Context, Result};

use crate::course::{Course, Exercise};

const MANIFEST_HEADER: &str = r#"# Generated by `cargo rusty`; don't edit (it's rewritten as exercises unlock).
# Your exercise files are the .rs files in the folders next to this one.
[package]
name = "work"
version = "0.0.0"
edition = "2024"
publish = false
autobins = false
autoexamples = false
autotests = false
autobenches = false

[lints.rust]
# Exercise code is often only used by the tests.
dead_code = "allow"

# A standalone workspace (and lockfile) of its own.
[workspace]
"#;

/// Copies the exercise's starting point into `work/` if it isn't there yet.
pub fn ensure_exercise(course: &Course, ex: &Exercise) -> Result<()> {
    if !ex.work.exists() {
        copy_stub(ex)?;
    }
    sync_manifest(course)
}

/// Overwrites the working copy with the pristine starting point.
pub fn reset(course: &Course, ex: &Exercise) -> Result<()> {
    copy_stub(ex)?;
    sync_manifest(course)
}

/// Puts back the original tests section, keeping the learner's code above it.
pub fn restore_tests(ex: &Exercise) -> Result<()> {
    let code = fs::read_to_string(&ex.work)?;
    let stub = fs::read_to_string(&ex.stub)?;
    let tests = tests_section(&stub).context("this exercise has no tests section")?;
    let head = code_section(&code).trim_end();
    fs::write(&ex.work, format!("{head}\n\n{tests}"))?;
    Ok(())
}

fn copy_stub(ex: &Exercise) -> Result<()> {
    if let Some(dir) = ex.work.parent() {
        fs::create_dir_all(dir)?;
    }
    fs::copy(&ex.stub, &ex.work)
        .with_context(|| format!("copying {} to {}", ex.stub.display(), ex.work.display()))?;
    Ok(())
}

/// Regenerates `work/Cargo.toml` with one bin target per unlocked exercise.
pub fn sync_manifest(course: &Course) -> Result<()> {
    let work_dir = course.work_dir();
    let mut manifest = String::from(MANIFEST_HEADER);
    manifest.push_str(&dependencies_section(course)?);
    for ex in course.exercises().filter(|e| e.work.exists()) {
        let rel = ex.work.strip_prefix(&work_dir).unwrap_or(&ex.work);
        manifest.push_str(&bin_section(&ex.bin(), rel));
    }
    fs::create_dir_all(&work_dir)?;
    write_if_changed(&work_dir.join("Cargo.toml"), &manifest)?;
    Ok(())
}

pub fn dependencies_section(course: &Course) -> Result<String> {
    if course.dependencies.is_empty() {
        return Ok(String::new());
    }
    Ok(format!(
        "\n[dependencies]\n{}",
        toml::to_string(&course.dependencies)?
    ))
}

pub fn bin_section(name: &str, path: &Path) -> String {
    let path = path.to_string_lossy().replace('\\', "/");
    format!(
        "\n[[bin]]\nname = {}\npath = {}\n",
        toml::Value::from(name),
        toml::Value::from(path)
    )
}

/// Writes only when the content differs, so Cargo doesn't see a needless change.
pub fn write_if_changed(path: &Path, contents: &str) -> Result<bool> {
    if fs::read_to_string(path).is_ok_and(|old| old == contents) {
        return Ok(false);
    }
    fs::write(path, contents).with_context(|| format!("writing {}", path.display()))?;
    Ok(true)
}

const TESTS_MARKER: &str = "\n#[cfg(test)]";

fn split(code: &str) -> (&str, Option<&str>) {
    match code.rfind(TESTS_MARKER) {
        Some(i) => (&code[..=i], Some(&code[i + 1..])),
        None => (code, None),
    }
}

/// Everything from the last top-level `#[cfg(test)]` to the end of the file.
pub fn tests_section(code: &str) -> Option<&str> {
    split(code).1
}

/// Everything above the tests section.
pub fn code_section(code: &str) -> &str {
    split(code).0
}

/// The text without any whitespace, so reformatting doesn't count as a change.
pub fn squash(text: &str) -> String {
    text.chars().filter(|c| !c.is_whitespace()).collect()
}
